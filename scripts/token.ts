/**
 * Generate the shared bearer token and write the mIRC-side config.
 *
 * Both doors use one secret, so this is the single place it is minted. The
 * generated `bridge.ini` is gitignored: it is a credential, not source.
 */

import { ConfigError } from "../src/config.ts";
import { readIniValue } from "../src/core/ini.ts";

const INI_PATH = "mirc/bridge.ini";

function generateToken(bytes = 32): string {
  const buffer = new Uint8Array(bytes);
  crypto.getRandomValues(buffer);
  return Array.from(buffer, (b) => b.toString(16).padStart(2, "0")).join("");
}

async function existingToken(): Promise<string | undefined> {
  try {
    return readIniValue(await Deno.readTextFile(INI_PATH), "bridge", "token");
  } catch {
    return undefined;
  }
}

function usage(): void {
  console.log(
    [
      "Usage: deno task token [--force] [--host H] [--port N]",
      "",
      "  --force   regenerate even when mirc/bridge.ini already has a token",
      "  --host    address mIRC should dial (default 127.0.0.1)",
      "  --port    port mIRC should dial (default 8686)",
    ].join("\n"),
  );
}

if (import.meta.main) {
  const argv = Deno.args;
  if (argv.includes("--help") || argv.includes("-h")) {
    usage();
    Deno.exit(0);
  }

  const flag = (name: string): string | undefined => {
    const index = argv.indexOf(`--${name}`);
    if (index !== -1 && argv[index + 1] && !argv[index + 1].startsWith("--")) {
      return argv[index + 1];
    }
    const inline = argv.find((a) => a.startsWith(`--${name}=`));
    return inline?.slice(name.length + 3);
  };

  const force = argv.includes("--force");
  const previous = await existingToken();

  if (previous && !force) {
    console.log(`${INI_PATH} already has a token. Use --force to replace it.`);
    console.log("");
    console.log(`  token: ${previous}`);
    console.log("");
    console.log("Point mIRC at it by loading mirc/bridge.mrc (see mirc/remote.ini.snippet),");
    console.log("and give the same value to agents as MIRC_DAEMON_TOKEN.");
    Deno.exit(0);
  }

  const host = flag("host") ?? "127.0.0.1";
  const port = flag("port") ?? "8686";
  const portNumber = Number(port);
  if (!Number.isInteger(portNumber) || portNumber < 1 || portNumber > 65535) {
    throw new ConfigError(`--port must be a valid port number, got "${port}"`);
  }

  const token = generateToken();
  await Deno.mkdir("mirc", { recursive: true });
  // CRLF deliberately: mIRC on Windows reads this with its own INI parser, and
  // this file is consumed there, not by us.
  await Deno.writeTextFile(
    INI_PATH,
    [
      "; Read by bridge.mrc. Generated by `deno task token` -- do not commit this file.",
      "[bridge]",
      `host=${host}`,
      `port=${portNumber}`,
      `token=${token}`,
      "",
    ].join("\r\n"),
  );

  console.log(`Wrote ${INI_PATH}`);
  console.log("");
  console.log(`  token: ${token}`);
  console.log("");
  console.log(`Make sure the daemon's --mirc-addr matches ${host}:${portNumber} (it is the`);
  console.log("default), and give agents the same token as MIRC_DAEMON_TOKEN:");
  console.log("");
  console.log(`  MIRC_DAEMON_TOKEN=${token}`);
}
